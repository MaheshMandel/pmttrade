// @ts-check
import { defineConfig } from "astro/config";
import tailwindcss from "@tailwindcss/vite";
import sitemap from "@astrojs/sitemap";
import { existsSync, readFileSync } from "node:fs";
import { execSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import path from "node:path";

import { LOCALES, DEFAULT_LOCALE, LOCALE_HREFLANG } from "./src/i18n/config";

const SITE = "https://pickmytrade.trade";

const PROJECT_ROOT = path.dirname(fileURLToPath(import.meta.url));
const PAGES_BASE = path.join(PROJECT_ROOT, "src/pages/[...locale]");

/** @type {Map<string, string>} */
const lastmodCache = new Map();

function resolvePageFile(routePath) {
  if (routePath === "") return path.join(PAGES_BASE, "index.astro");
  const direct = path.join(PAGES_BASE, `${routePath}.astro`);
  if (existsSync(direct)) return direct;
  const indexed = path.join(PAGES_BASE, routePath, "index.astro");
  if (existsSync(indexed)) return indexed;
  return null;
}

function getLastmod(routePath) {
  const file = resolvePageFile(routePath);
  if (!file) return undefined;
  if (lastmodCache.has(file)) return lastmodCache.get(file);

  let lastmod;
  try {
    const out = execSync(`git log -1 --format=%aI -- "${file}"`, {
      cwd: PROJECT_ROOT,
      stdio: ["ignore", "pipe", "ignore"],
    })
      .toString()
      .trim();
    lastmod = out || undefined;
  } catch {
    lastmod = undefined;
  }

  lastmodCache.set(file, lastmod);
  return lastmod;
}

function routePathFromUrl(url) {
  const segments = new URL(url).pathname.split("/").filter(Boolean);
  if (segments.length && LOCALES.includes(segments[0]) && segments[0] !== DEFAULT_LOCALE) {
    segments.shift();
  }
  return segments.join("/");
}

// Non-English versions of the templated partner-review pages (PartnerPage.astro)
// carry a noindex directive — see BaseLayout robots prop on these pages. Keep the
// sitemap in sync so Search Console never sees a submitted URL marked noindex.
const NOINDEXED_LOCALIZED_PARTNER_ROUTES = new Set([
  "babypips", "barchart", "benzinga", "bigbeluga", "bookmap",
  "canadian-futures-trader", "forex-factory", "luxalgo", "marketwatch",
  "pinecoders", "prop-firm-match", "stockcharts", "theindicatorstore",
  "thetrustedprop", "traderlion", "tradezella", "trading-economics",
  "yahoo-finance", "zeiierman",
]);

function isNoindexedLocalizedPartnerPage(url) {
  const segments = new URL(url).pathname.split("/").filter(Boolean);
  const hasLocalePrefix = segments.length && LOCALES.includes(segments[0]) && segments[0] !== DEFAULT_LOCALE;
  if (!hasLocalePrefix) return false;
  return NOINDEXED_LOCALIZED_PARTNER_ROUTES.has(segments[1]);
}

// debugging/ and how-to/ guide pages whose screenshots haven't been shot yet —
// BaseLayout robots="noindex, follow" on these pages (all locales) keeps them out
// of search results until images are added. Keep the sitemap in sync so Search
// Console never sees a submitted URL marked noindex. Remove an entry here once
// its screenshots are added and the robots prop is removed from the page.
const NOINDEXED_GUIDE_ROUTES = new Set([]);

function isNoindexedGuidePage(url) {
  return NOINDEXED_GUIDE_ROUTES.has(routePathFromUrl(url));
}

// FE-29: locale copies of guides that are still English text are noindexed by
// BaseLayout, so keep them (and hreflang links to them) out of the sitemap too.
// Generated by scripts/find-untranslated-guides.mjs (runs before every build).
const UNTRANSLATED_GUIDES = JSON.parse(
  readFileSync(path.join(PROJECT_ROOT, "src/data/untranslatedGuides.json"), "utf8"),
);
function isUntranslatedLocaleGuide(url) {
  const segments = new URL(url).pathname.split("/").filter(Boolean);
  if (!segments.length || segments[0] === DEFAULT_LOCALE || !LOCALES.includes(segments[0])) return false;
  return (UNTRANSLATED_GUIDES[segments.slice(1, 3).join("/")] ?? []).includes(segments[0]);
}

export default defineConfig({
  site: SITE,

  output: "static",

  i18n: {
    locales: [...LOCALES],
    defaultLocale: DEFAULT_LOCALE,
    routing: {
      prefixDefaultLocale: false,
      redirectToDefaultLocale: false,
    },
  },

  integrations: [
    sitemap({
      // hreflang language tags must match the on-page <link rel="alternate"> tags (bare en / de, not en-US / de-DE)
      i18n: {
        defaultLocale: DEFAULT_LOCALE,
        locales: Object.fromEntries(LOCALES.map((l) => [l, LOCALE_HREFLANG[l]])),
      },
      filter: (page) => !isNoindexedLocalizedPartnerPage(page) && !isNoindexedGuidePage(page) && !isUntranslatedLocaleGuide(page),
      // per-page lastmod from each source file's last git commit date, so recently
      // changed pages carry a real freshness signal instead of all 325 URLs looking identical
      serialize(item) {
        const lastmod = getLastmod(routePathFromUrl(item.url));
        const result = lastmod ? { ...item, lastmod } : item;

        // Drop hreflang alternates pointing at the noindexed locale versions of the
        // partner pages, so the entry doesn't reference URLs excluded above.
        if (result.links?.length) {
          result.links = result.links.filter(
            (l) => !isNoindexedLocalizedPartnerPage(l.url) && !isNoindexedGuidePage(l.url) && !isUntranslatedLocaleGuide(l.url),
          );
        }

        // @astrojs/sitemap's i18n option doesn't emit an x-default alternate, but
        // BaseLayout's on-page <link rel="alternate" hreflang="x-default"> does — keep
        // the sitemap in parity by pointing x-default at the default-locale URL.
        if (result.links?.length && !result.links.some((l) => l.lang === "x-default")) {
          const defaultLink = result.links.find((l) => l.lang === LOCALE_HREFLANG[DEFAULT_LOCALE]);
          if (defaultLink) {
            result.links = [...result.links, { lang: "x-default", url: defaultLink.url }];
          }
        }

        return result;
      },
    }),
  ],

  vite: {
    // @ts-ignore — @tailwindcss/vite plugin type is compatible at runtime
    plugins: [tailwindcss()],
  },

  build: {
    inlineStylesheets: "auto",
  },
});
